"""Пользовательский текст в сообщениях: экранирование и лимиты длины.

Бот шлёт всё с parse_mode=HTML, поэтому любой текст от пользователя (ник, ТЗ,
названия работ, подписи) подставляется в шаблоны только через esc(): иначе «<»
в ТЗ ломает отправку, а «<a href=...>» вставляет в группу чужую ссылку.

Лимиты ввода подобраны так, чтобы самые длинные сообщения (тендер, карточка
заказа, заявка исполнителя) влезали в 4096 символов, а подписи к медиа — в 1024.
"""
from html import escape

# Ответ на шаг ТЗ: до 6 шагов × 500 + обвязка карточки заказа < 4096.
BRIEF_FIELD_MAX = 500
# Заявка исполнителя: услуга 128 + опыт 1500 + портфолио 1500 + обвязка < 4096.
SERVICE_MAX = 128
EXPERIENCE_MAX = 1500
PORTFOLIO_LINKS_MAX = 1500
SOCIALS_MAX = 1000
# Подпись элемента портфолио вместе с «🖼 Портфолио N/M» < 1024.
PORTFOLIO_CAPTION_MAX = 900
# Вопрос по работе вместе с заголовком < 4096.
QUESTION_MAX = 3000


def esc(value, default: str = "—", limit: int | None = None) -> str:
    """Экранирует пользовательский текст для HTML; пустое значение → default.

    limit обрезает сырой текст (до экранирования, чтобы не разрезать «&lt;») —
    страховка для записей, сохранённых до появления лимитов ввода.
    """
    if value is None or value == "":
        return default
    text = str(value)
    if limit is not None and len(text) > limit:
        text = text[: limit - 1] + "…"
    return escape(text, quote=False)
